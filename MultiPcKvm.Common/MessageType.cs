namespace MultiPcKvm.Common
{
    // 두 PC가 주고받을 메시지의 "종류" 목록.
    //
    // 네트워크로는 숫자만 오간다. 그래서 "1번이 오면 마우스 이동"이라고
    // 양쪽이 미리 약속해둬야 대화가 된다. 그 약속표가 이 파일이다.
    //
    // 숫자를 직접 붙인 이유:
    //   숫자를 안 쓰면 C#이 위에서부터 0, 1, 2... 로 자동으로 매긴다.
    //   그러면 나중에 항목을 중간에 끼워넣거나 순서를 바꿨을 때
    //   같은 숫자가 다른 뜻이 돼버려서, 구버전 PC와 신버전 PC가
    //   서로 엉뚱하게 해석하게 된다.
    //
    // 규칙: 여기 있는 숫자는 절대 바꾸지 말고, 새 항목은 항상 뒤에 추가한다.
    public enum MessageType
    {
        MouseMove = 1,      // 마우스가 움직였다        (Value1=X, Value2=Y)
        MouseButton = 2,    // 마우스 버튼을 누르거나 뗐다 (Value1=버튼번호, Value2=누름1/뗌0)
        KeyDown = 3,        // 키를 눌렀다              (Value1=키번호)
        KeyUp = 4,          // 키를 뗐다                (Value1=키번호)

        // 마우스가 "얼마나" 움직였다        (Value1=가로 이동량, Value2=세로 이동량)
        //
        // MouseMove 와 뭐가 다른가:
        //   MouseMove       = "(500, 300) 으로 가라"   ← 목적지
        //   MouseMoveDelta  = "오른쪽으로 3, 아래로 1" ← 이동량
        //
        // 왜 둘 다 필요한가:
        //   커서가 상대 PC에 가 있는 동안에는 내 PC의 커서를 한 자리에 묶어둔다.
        //   그러면 내 화면 좌표는 의미가 없어지므로 이동량만 전달할 수 있다.
        //
        // 주의:
        //   이 메시지는 내 PC 안에서만 쓴다 (가로채는 쪽 → 판단하는 쪽).
        //   네트워크로 내보낼 때는 상대 화면 기준 좌표로 바꿔서 MouseMove 로 보낸다.
        //   상대 PC는 자기 화면 좌표만 알면 되고, 내가 얼마나 움직였는지는 알 필요가 없다.
        MouseMoveDelta = 5,


        // ── 연결 확인용 ───────────────────────────────────────
        //
        // 입력이 아니라 "아직 살아있냐" 를 묻고 답하는 메시지다.
        //
        // 왜 필요한가:
        //   TCP 로 메시지를 보내는 데 성공해도 상대가 받았다는 보장이 없다.
        //   보낸 데이터는 일단 OS 버퍼에 들어가고, 실패는 한참 뒤에 드러난다.
        //   그래서 직접 물어보고 답을 받아야 연결이 살아있는지 알 수 있다.
        //
        //   이게 안 되면: 상대 PC 전원이 나갔는데도 계속 삼키기를 유지해서
        //   내 키보드·마우스가 죽은 채로 남는다.

        // "살아있냐?"        (Value1 = 이번 질문의 번호)
        //
        // 번호를 붙이는 이유:
        //   여러 번 물어보면 답이 뒤섞여 돌아올 수 있다.
        //   3번 질문의 답인지 5번 질문의 답인지 알아야
        //   왕복 시간을 정확히 잴 수 있다.
        Ping = 6,

        // "살아있다"          (Value1 = 받은 질문 번호를 그대로 돌려줌)
        //
        // 시각을 담지 않고 번호만 주고받는 이유:
        //   두 PC의 시계가 몇 초씩 다를 수 있다.
        //   보낸 시각은 내 PC 안에 기억해두고, 답이 오면 그때 계산하면
        //   상대 시계가 틀려도 상관없다.
        Pong = 7,


        // ── 화면 정보 ─────────────────────────────────────────

        // "내 화면은 이만큼이다"   (Value1 = 가로, Value2 = 세로)
        //
        // 왜 필요한가:
        //   커서가 경계를 넘을 때 상대 화면 기준 좌표로 환산해야 하는데,
        //   상대 화면이 몇 픽셀인지 모르면 계산이 안 된다.
        //
        //   손으로 입력받을 수도 있지만 사용자가 자기 해상도를
        //   정확히 아는 경우가 드물고, 모니터를 바꾸면 또 틀어진다.
        //   그래서 연결되면 서로 알려준다.
        //
        // 주기적으로 보낸다:
        //   한 번만 보내면 그 메시지가 유실됐을 때 영영 모른다.
        //   몇 초마다 다시 보내면 중간에 해상도를 바꿔도 따라간다.
        ScreenInfo = 8,


        // ── 연결 승인 (페어링) ────────────────────────────────
        //
        // 같은 공유기에 붙은 사람이면 누구나 검색에 잡힌다.
        // 그대로 두면 남의 PC 를 마음대로 조종할 수 있게 된다.
        //
        // 그래서 조종당하는 쪽 화면에 4자리 코드를 띄우고,
        // 조종하려는 쪽이 그 코드를 입력하게 한다.
        //
        // 이 방향이어야 "그 PC 화면을 볼 수 있는 사람만 연결할 수 있다" 가
        // 성립한다. 반대로 하면 조종당하는 쪽이 타이핑을 해야 하는데,
        // 키보드가 없는 PC 를 조종하려는 경우도 있어서 곤란하다.

        // "코드는 이거다. 연결해도 되나?"   (Value1 = 4자리 코드)
        PairRequest = 9,

        // "맞다 / 틀리다"
        //   Value1 = 1  승인
        //            0  코드가 틀림
        //            2  코드는 상관없이 지금은 안 됨
        //               (이 PC 가 이미 다른 쪽을 조종 중이거나, 연결을 거는 중)
        //            3  저장된 기기 열쇠(PairTokenRequest)가 맞지 않음
        //               → 보낸 쪽은 열쇠를 버리고 코드 입력으로 돌아간다
        //                 (상대가 나를 저장된 기기에서 지웠거나, 상대 DB 가 새로 만들어진 경우)
        //
        // 2 를 따로 둔 이유:
        //   0 하나로 뭉치면 거절당한 쪽에 "코드가 틀렸다" 고 뜬다.
        //   사용자는 코드를 몇 번이고 다시 치게 되고 진짜 이유는 못 찾는다.
        //
        // ※ 예전 버전은 1 이 아니면 전부 "틀림" 으로 보여준다. 동작은 문제없다.
        PairResult = 10,

        // "이제 그만 조종할게"              (값 없음)
        //
        // 연결 끊기를 누르면 상대에게 이걸 보낸다.
        // 받은 쪽도 자기가 나를 조종하던 중이면 같이 멈춘다.
        //
        // TCP 줄을 그냥 끊으면 안 되는 이유:
        //   상대는 "갑자기 끊겼다" 로 받아들이고 자동으로 다시 붙어버린다.
        //   "사고로 끊김" 과 "일부러 끊음" 을 구분하려면 이 신호가 필요하다.
        Unpair = 11,


        // ── 저장된 기기: 코드 없이 연결 ────────────────────────
        //
        // 한 번 코드를 통과하면, 조종당하는 쪽이 "열쇠"(64비트 무작위 수)를 하나 만들어 준다.
        // 다음부터는 코드 대신 이 열쇠를 보내서 연결한다.
        //
        //   처음 (코드)          A ── Hello(내 ID) ──────────▶ B
        //                       A ── PairRequest(코드) ─────▶ B
        //                       A ◀── PairResult(1) ──────── B
        //                       A ◀── PairTokenGrant(열쇠) ── B   B 는 "A 가 낼 열쇠" 로 저장
        //                                                       A 는 "B 에게 낼 열쇠" 로 저장
        //   다음부터 (열쇠)       A ── Hello(내 ID) ──────────▶ B
        //                       A ── PairTokenRequest(열쇠) ▶ B   B 는 A 의 저장된 열쇠와 비교
        //                       A ◀── PairResult(1 또는 3) ── B
        //
        // 열쇠는 방향마다 따로다. A 가 B 를 조종하려고 받은 열쇠로 B 가 A 를 조종할 수는 없다.
        // (B 가 A 를 조종하려면 A 화면의 코드를 한 번 입력해야 한다)
        //
        // 값 하나(int)가 32비트라, 64비트 값은 Value1(위 32비트) + Value2(아래 32비트) 로 나눠 담는다.
        // 기기 ID(GUID, 128비트)는 두 번에 나눠 보낸다.

        // "나는 이 기기다" 앞쪽 절반       (Value1, Value2 = 기기 ID 의 0~7 바이트)
        HelloIdHigh = 12,

        // "나는 이 기기다" 뒤쪽 절반       (Value1, Value2 = 기기 ID 의 8~15 바이트)
        //
        // 조종당하는 쪽은 이걸로 누가 연결하려는지 안다.
        // 예전에는 대기 상태가 향한 기기(처음 검색된 기기)를 상대로 여겨서,
        // 기기가 셋 이상이면 엉뚱한 이름이 뜨고 엉뚱한 기기가 저장될 수 있었다.
        HelloIdLow = 13,

        // "코드 대신 이 열쇠로 연결할게"   (Value1, Value2 = 열쇠)
        PairTokenRequest = 14,

        // "다음부터는 이 열쇠를 써"        (Value1, Value2 = 열쇠)
        //   코드로 연결을 승인한 직후 조종당하는 쪽이 보낸다.
        PairTokenGrant = 15,


        // ── 마우스 휠 ─────────────────────────────────────────
        //
        // "휠을 굴렸다"   (Value1 = 굴린 양, Value2 = 0 세로 휠 / 1 가로 휠)
        //
        // 굴린 양은 Windows 값 그대로다. 한 칸 = 120.
        //   세로: 위로(멀리) 굴리면 +120, 아래로(가까이) 굴리면 -120
        //   가로: 오른쪽 +120, 왼쪽 -120
        //   고급 마우스는 120 보다 작은 값으로 여러 번 온다. (부드러운 스크롤)
        //
        // 휠 누르기(클릭)는 이게 아니라 MouseButton 의 3번(가운데 버튼)이다.
        MouseWheel = 16,


        // ── 파일 받기 요청 ────────────────────────────────────
        //
        // "보낼 파일을 하나 골라서 나한테 보내줘"   (값 없음)
        //
        // 조종하는 쪽의 [파일 받기] 버튼이 보낸다.
        // 받은 쪽(조종당하는 PC)은 화면에 파일 고르기 창을 띄운다.
        // 조종하는 사람이 화면 보기 창으로 그 창을 보면서 고르면, 그 파일을 보내준다.
        // (파일 데이터는 이 줄이 아니라 파일 전송 포트로 간다. FileTransfer.cs 참고)
        FileRequest = 17
    }
}
