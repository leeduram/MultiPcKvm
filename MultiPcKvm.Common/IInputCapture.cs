using System;

namespace MultiPcKvm.Common
{
    // ─────────────────────────────────────────────────────────────
    //  Windows 담당(이두람)이 만들 것의 설계도 ① — 입력을 "가로채는" 쪽
    // ─────────────────────────────────────────────────────────────
    //
    // 내 PC의 마우스/키보드 움직임을 붙잡아서 InputMessage 로 바꿔주는 역할.
    // 실제 구현은 Windows 의 Low-Level Hook 을 쓰지만,
    // 이 설계도를 쓰는 쪽은 그런 걸 몰라도 된다.
    //
    // 구현 예정: WindowsInputCapture
    public interface IInputCapture
    {
        // 마우스가 움직이거나 키를 누를 때마다 발생한다.
        event Action<InputMessage>? InputCaptured;

        // true 로 바꾸면 입력을 이 PC에 전달하지 않고 삼켜버린다.
        //
        // 커서가 상대 PC로 넘어가 있는 동안 반드시 true 여야 한다.
        // 안 그러면 내 화면의 커서도 같이 움직여서, 두 PC의 커서가
        // 동시에 움직이는 이상한 상태가 된다.
        //
        // ⚠️ 켜면 이 PC의 키보드·마우스가 완전히 안 먹는다.
        //    반드시 아래 KeepAlive 와 같이 써야 한다.
        bool SwallowInput { get; set; }

        // "아직 정상입니다" 신호.
        //
        // 삼키기를 켜둔 동안에는 이것을 주기적으로(예: 0.5초마다) 불러야 한다.
        // 일정 시간(기본 2초) 동안 안 부르면 삼키기가 자동으로 풀린다.
        //
        // 왜 이런 방식인가:
        //   프로그램이 멈추는 이유는 수없이 많다.
        //   네트워크 끊김, 예외, 데드락, 상대 PC 꺼짐...
        //   그걸 하나하나 감지하려면 끝이 없고, 빠뜨린 하나 때문에
        //   키보드가 죽은 채로 남는다.
        //
        //   반대로 뒤집으면 간단해진다.
        //   "정상일 때만 신호를 보낸다. 신호가 끊기면 그게 고장이다."
        //   무슨 이유로 멈췄든 상관없이 전부 걸린다.
        //
        //   기차 기관사가 일정 시간마다 버튼을 안 누르면
        //   열차가 자동으로 멈추는 장치와 같은 원리다.
        void KeepAlive();

        // 가로채기 시작
        void Start();

        // 가로채기 중지 (삼키기도 같이 풀린다)
        void Stop();
    }
}
